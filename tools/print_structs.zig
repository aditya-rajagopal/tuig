const std = @import("std");
const helpers = @import("helpers.zig");

const cut = helpers.cut;
const cutScalar = helpers.cutScalar;

pub fn main() !void {
    var threaded = std.Io.Threaded.init_single_threaded;
    const io = threaded.ioBasic();
    const file = try std.Io.Dir.cwd().createFile(io, "src/tools/types.zig", .{});
    defer file.close(io);

    var buffer: [4096]u8 = undefined;
    var file_writer = file.writer(io, &buffer);
    const writer = &file_writer.interface;
    try writer.writeAll(
        \\//! DO NOT EDIT - This file is auto-generated by print_structs.zig
        \\
        \\
    );

    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    _ = arena.allocator().alloc(u8, 1 * 1024 * 1024) catch unreachable;
    _ = arena.reset(.retain_capacity);

    try printDerivedCorePropertiesStruct(io, arena.allocator(), writer);
    _ = arena.reset(.retain_capacity);

    try printEmojiStruct(io, arena.allocator(), writer);
    _ = arena.reset(.retain_capacity);

    try printGraphemeBreakEnum(io, arena.allocator(), writer);
    _ = arena.reset(.retain_capacity);

    try printEastAsianWidthEnum(io, arena.allocator(), writer);
    _ = arena.reset(.retain_capacity);

    try printGeneralCategoryEnum(io, arena.allocator(), writer);
}

pub fn printGeneralCategoryEnum(io: std.Io, allocator: std.mem.Allocator, writer: *std.Io.Writer) !void {
    var file = try std.Io.Dir.cwd().openFile(io, "UCD/extracted/DerivedGeneralCategory.txt", .{});
    defer file.close(io);
    var file_buffer: [4096]u8 = undefined;
    var file_reader = file.reader(io, &file_buffer);
    const reader = &file_reader.interface;
    var property_map = std.StringArrayHashMap(void).init(allocator);
    while (true) : (_ = try reader.discardDelimiterInclusive('\n')) {
        const first_byte = reader.peekByte() catch |err| switch (err) {
            error.EndOfStream => break,
            else => |e| return e,
        };
        if (first_byte == '\n') continue;
        if (first_byte == '#') continue;
        const line = try reader.takeDelimiterExclusive('#');
        _, var property = if (cutScalar(u8, line, ';')) |result| result else return error.InvalidLine;
        property = std.mem.trim(u8, property, " \t");
        if (property_map.get(property)) |_| {
            continue;
        } else {
            try property_map.putNoClobber(try allocator.dupe(u8, property), {});
        }
    }

    const count = property_map.count();
    try writer.print("pub const GeneralCategory = enum(u{d}) {{\n", .{std.math.log2_int_ceil(usize, count)});
    for (property_map.keys()) |key| {
        try writer.print("    {s},\n", .{key});
    }
    try writer.writeAll("};\n\n");
    try writer.flush();
}

