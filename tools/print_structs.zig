pub fn printDerivedCorePropertiesStruct(io: std.Io, allocator: std.mem.Allocator, writer: *std.Io.Writer) !void {
    var file = try std.Io.Dir.cwd().openFile(io, "UCD/DerivedCoreProperties.txt", .{});
    defer file.close(io);
    var file_buffer: [4096]u8 = undefined;
    var file_reader = file.reader(io, &file_buffer);
    const reader = &file_reader.interface;
    var property_map = std.StringArrayHashMap(void).init(allocator);
    var value_map = std.StringArrayHashMap(void).init(allocator);
    while (true) : (_ = try reader.discardDelimiterInclusive('\n')) {
        const first_byte = reader.peekByte() catch |err| switch (err) {
            error.EndOfStream => break,
            else => |e| return e,
        };
        if (first_byte == '\n') continue;
        if (first_byte == '#') {
            const search = "# Derived Property: ";
            var start = reader.peek(search.len) catch |err| switch (err) {
                error.EndOfStream => break,
                else => |e| return e,
            };
            if (std.mem.eql(u8, start, search)) {
                reader.toss(search.len);
                var property: []const u8 = try reader.takeDelimiterExclusive('\n');
                property = std.mem.trim(u8, property, " \t");
                property, _ = if (cutScalar(u8, property, ' ')) |result| result else .{ property, &.{} };
                property = std.mem.trim(u8, property, " \t()");
                if (std.mem.eql(u8, property, "Indic_Conjunct_Break")) {
                    property = "InCB";
                }
                try property_map.putNoClobber(try allocator.dupe(u8, property), {});
                continue;
            }
            const incb_value_str = "# Indic_Conjunct_Break=";
            start = reader.peek(incb_value_str.len) catch |err| switch (err) {
                error.EndOfStream => break,
                else => |e| return e,
            };
            if (std.mem.eql(u8, start, incb_value_str)) {
                reader.toss(incb_value_str.len);
                var property: []const u8 = try reader.takeDelimiterExclusive('\n');
                property = std.mem.trim(u8, property, " \t");
                try value_map.putNoClobber(try allocator.dupe(u8, property), {});
            }
        }
    }
    const count = property_map.count();
    const values_bits = std.math.log2_int_ceil(usize, value_map.count() + 1);
    try writer.print("pub const DerivedCorePropertiesBacking = u{d};\n\n", .{count + values_bits - 1});
    try writer.writeAll("pub const DerivedCoreProperties = packed struct(DerivedCorePropertiesBacking) {\n");
    for (property_map.keys()) |key| {
        if (std.mem.eql(u8, key, "InCB")) {
            try writer.print("    {s}: IndicConjunctBreakValue = .None,\n", .{key});
            continue;
        }
        try writer.print("    {s}: bool = false,\n", .{key});
    }
    try writer.writeAll("};\n\n");
    try writer.writeAll("pub const DerivedCorePropertiesMask = enum(DerivedCorePropertiesBacking) {\n");
    for (property_map.keys(), 0..) |key, i| {
        try writer.print("    {s} = 0b{b},\n", .{ key, @as(usize, 1) << @intCast(i) });
    }
    try writer.writeAll("};\n\n");
    try writer.print("pub const IndicConjunctBreakValue = enum(u{d}) {{\n", .{values_bits});
    try writer.writeAll("    None,\n");
    for (value_map.keys()) |key| {
        try writer.print("    {s},\n", .{key});
    }
    try writer.writeAll("};\n\n");
    try writer.flush();
}
